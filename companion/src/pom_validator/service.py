import asyncio
import hmac
import json
import logging
import platform
import re
import threading
from concurrent.futures import TimeoutError as FutureTimeout
from dataclasses import dataclass
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from importlib.metadata import version

from . import PROTOCOL, VERSION
from .browser import BrowserConnection, BrowserUnavailable, PageUnavailable
from .contracts import STRATEGIES, RequestError, ValidationRequest, object_value, string
from .validation import measure, unavailable

LOG = logging.getLogger(__name__)
MAX_BYTES = 128 * 1024


@dataclass(frozen=True)
class Settings:
    port: int
    debugger_port: int
    origin: str
    token: str

    def __post_init__(self) -> None:
        if not 1024 <= self.port <= 65535 or not 1024 <= self.debugger_port <= 65535:
            raise ValueError("Use ports between 1024 and 65535.")
        if self.port == self.debugger_port:
            raise ValueError("The service and debugging ports must differ.")
        if not re.fullmatch(r"chrome-extension://[a-p]{32}", self.origin):
            raise ValueError("Provide the exact chrome-extension:// origin.")
        if not re.fullmatch(r"[A-Za-z0-9_-]{43}", self.token):
            raise ValueError("Use a token generated by pom-validator token.")


class Service:
    def __init__(self, settings: Settings) -> None:
        self.connection = BrowserConnection(settings.debugger_port)
        self.lock = asyncio.Lock()
        self.pending: dict[str, asyncio.Task] = {}

    def status(self) -> dict:
        connection = self.connection
        return {
            "serviceVersion": VERSION,
            "playwrightVersion": version("playwright"),
            "pythonVersion": platform.python_version(),
            "strategies": STRATEGIES,
            "connected": connection.connected,
            "browserId": connection.identity if connection.connected else None,
            "browserVersion": connection.browser.version
            if connection.connected and connection.browser
            else None,
        }

    async def dispatch(self, route: str, body: dict) -> tuple[int, dict]:
        try:
            if type(body.get("protocol")) is not int or body["protocol"] != PROTOCOL:
                return 409, {
                    "error": "protocol",
                    "message": "Use a protocol v1 companion and extension.",
                }
            if route == "/status":
                return 200, self.status()
            if route == "/cancel":
                task = self.pending.get(string(body.get("requestId"), "request ID", 80))
                if task:
                    task.cancel()
                return 200, {"cancelled": task is not None}
            if route in ("/connect", "/disconnect"):
                if route == "/disconnect":
                    for task in list(self.pending.values()):
                        task.cancel()
                async with self.lock:
                    if route == "/connect":
                        await self.connection.connect()
                    else:
                        await self.connection.disconnect()
                return 200, self.status()
            if route != "/validate":
                return 404, {
                    "error": "route",
                    "message": "Unknown companion operation.",
                }
            request = ValidationRequest.parse(body)
            if self.pending or self.lock.locked():
                return 429, {
                    "error": "busy",
                    "message": "The companion is already handling another operation.",
                }
            task = asyncio.create_task(self.validate(request))
            self.pending[request.request_id] = task
            try:
                return 200, await task
            except asyncio.CancelledError:
                return 409, {
                    "error": "cancelled",
                    "message": "Validation was cancelled.",
                }
            finally:
                self.pending.pop(request.request_id, None)
        except RequestError as error:
            return 400, {"error": "request", "message": str(error)}
        except BrowserUnavailable as error:
            return 503, {"error": "connection", "message": str(error)}
        except PageUnavailable as error:
            return 409, {"error": "correlation", "message": str(error)}
        except TimeoutError:
            return 504, {
                "error": "timeout",
                "message": "The companion operation timed out.",
            }

    async def validate(self, request: ValidationRequest) -> dict:
        async with self.lock:
            connection = self.connection
            if request.browser_id != connection.identity or not connection.connected:
                raise BrowserUnavailable(
                    "The browser session changed. Reconnect and retry."
                )
            async with asyncio.timeout(3):
                page = await connection.page(request.correlation)
            results = []
            assert connection.driver is not None
            deadline = asyncio.get_running_loop().time() + 9
            # Playwright selector configuration is driver-global.
            for spec in request.locators:
                try:
                    async with asyncio.timeout_at(deadline):
                        attributes = spec.test_id_attributes()
                        if len(attributes) > 1:
                            results.append(
                                {
                                    **unavailable(spec),
                                    "status": "validation-error",
                                    "message": "Use one Playwright test ID attribute in a composed locator.",
                                }
                            )
                            continue
                        if attributes:
                            connection.driver.selectors.set_test_id_attribute(
                                next(iter(attributes))
                            )
                        results.append(await measure(page, spec, request))
                except TimeoutError:
                    results.append(unavailable(spec))
            return {
                "requestId": request.request_id,
                "browserId": request.browser_id,
                "documentKey": request.document_key,
                "results": results,
            }

    async def close(self) -> None:
        for task in list(self.pending.values()):
            task.cancel()
        async with self.lock:
            await self.connection.disconnect()


class LocalServer(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(
        self, settings: Settings, loop: asyncio.AbstractEventLoop, service: Service
    ) -> None:
        super().__init__(("127.0.0.1", settings.port), Handler)
        self.settings, self.loop, self.service = settings, loop, service
        self.slots = threading.BoundedSemaphore(8)

    def process_request(self, request, client_address) -> None:
        if not self.slots.acquire(blocking=False):
            self.shutdown_request(request)
            return
        try:
            request.settimeout(4)
            super().process_request(request, client_address)
        except BaseException:
            self.slots.release()
            raise

    def process_request_thread(self, request, client_address) -> None:
        try:
            super().process_request_thread(request, client_address)
        finally:
            self.slots.release()

    def handle_error(self, request, client_address) -> None:
        LOG.warning("event=http_transport_error")


class Handler(BaseHTTPRequestHandler):
    server: LocalServer

    def log_message(self, format: str, *args) -> None:
        pass

    def origin_allowed(self) -> bool:
        settings = self.server.settings
        host = f"127.0.0.1:{settings.port}"
        return self.headers.get_all("Host") == [host] and self.headers.get_all(
            "Origin"
        ) == [settings.origin]

    def do_OPTIONS(self) -> None:
        if not self.origin_allowed():
            self.reply(403, {"message": "Origin or Host is unauthorized."})
            return
        self.reply(204, {})

    def do_POST(self) -> None:
        settings = self.server.settings
        if not self.origin_allowed():
            self.reply(403, {"message": "Origin or Host is unauthorized."})
            return
        auth = self.headers.get_all("Authorization") or []
        if len(auth) != 1 or not hmac.compare_digest(
            auth[0].encode(), f"Bearer {settings.token}".encode()
        ):
            self.reply(
                401, {"message": "Pair with the companion using its local token."}
            )
            return
        if self.headers.get_all("Transfer-Encoding") or self.headers.get_all(
            "Content-Type"
        ) != ["application/json"]:
            self.reply(415, {"message": "Send a bounded JSON request."})
            return
        lengths = self.headers.get_all("Content-Length") or []
        if len(lengths) != 1 or not re.fullmatch(r"[0-9]{1,8}", lengths[0]):
            self.reply(400, {"message": "Provide a valid Content-Length."})
            return
        length = int(lengths[0])
        if length > MAX_BYTES:
            self.reply(413, {"message": "Request exceeds the companion size limit."})
            return
        if not self.path.startswith("/api/v1/"):
            self.reply(404, {"message": "Unknown protocol route."})
            return
        route = self.path[len("/api/v1") :]
        try:
            body = object_value(json.loads(self.rfile.read(length)))
        except (ValueError, UnicodeError, RecursionError):
            self.reply(400, {"message": "Invalid JSON request."})
            return
        future = asyncio.run_coroutine_threadsafe(
            self.server.service.dispatch(route, body), self.server.loop
        )
        try:
            code, result = future.result(timeout=14)
        except FutureTimeout:
            future.cancel()
            code, result = (
                504,
                {"error": "timeout", "message": "The companion operation timed out."},
            )
        except Exception:
            code, result = (
                500,
                {
                    "error": "internal",
                    "message": "The companion could not complete the operation.",
                },
            )
        operation = (
            route
            if route in ("/status", "/connect", "/disconnect", "/validate", "/cancel")
            else "unknown"
        )
        LOG.info("event=request operation=%s status=%s", operation, code)
        self.reply(code, result)

    def reply(self, code: int, value: dict) -> None:
        payload = (
            json.dumps({"protocol": PROTOCOL, **value}).encode() if code != 204 else b""
        )
        self.send_response(code)
        if self.origin_allowed():
            self.send_header("Access-Control-Allow-Origin", self.server.settings.origin)
            self.send_header(
                "Access-Control-Allow-Headers", "Authorization, Content-Type"
            )
            self.send_header("Access-Control-Allow-Methods", "POST, OPTIONS")
            self.send_header("Vary", "Origin")
        self.send_header("Content-Type", "application/json")
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)
